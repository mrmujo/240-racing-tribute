// Glyph slots. Å, Ä, Ö must be 26, 27, 28 (the engine special-cases their byte offsets).
const ORDER = [
  ..."ABCDEFGHIJKLMNOPQRSTUVWXYZ", "Å", "Ä", "Ö", ..."0123456789",
  ".", ",", "!", "?", "+", "-", "*", "/", ":", "'", "(", ")", '"', "%", "$", "=", "@", "#",
];
const BLANK = 57;

// 5x7 bitmaps -> the engine's 58 x (7x8) glyph data plus a '!'..'Z' offset table
export function buildFont() {
  const data = new Uint8Array(58 * 56);
  ORDER.forEach((ch, slot) => {
    const rows = G[ch];
    const on = (x, y) => y >= 0 && y < 7 && x >= 0 && x < 5 && rows[y][x] === "#";
    for (let y = 0; y < 8; y++)
      for (let x = 0; x < 7; x++) {
        let v = 0;
        if (on(x, y)) v = 16;
        else if (on(x - 1, y - 1)) v = 1;
        data[slot * 56 + y * 7 + x] = v;
      }
  });
  const table = [];
  for (let c = 0x21; c <= 0x5a; c++) {
    const slot = ORDER.indexOf(String.fromCharCode(c));
    table.push((slot < 0 ? BLANK : slot) * 56);
  }
  return { data, table };
}

// Same glyph shapes, for drawing big logo lettering
export function glyphRows(ch) {
  return G[ch] || null;
}
